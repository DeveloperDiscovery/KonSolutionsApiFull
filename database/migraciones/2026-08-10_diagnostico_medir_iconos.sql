DECLARE @COD_ROL_USUARIO VARCHAR(20) = 'SEG';   -- <<< AJUSTAR

PRINT '=== 1) BOTONES — el tercer resultado de TREEVIEWLOGOS ===';

SELECT
    Filas_Enviadas      = COUNT(*),
    Iconos_Distintos    = COUNT(DISTINCT HASHBYTES('SHA2_256', CAST(c.IMG_ICONO AS VARBINARY(MAX)))),
    MB_Enviados         = CAST(SUM(CAST(DATALENGTH(c.IMG_ICONO) AS BIGINT)) / 1048576.0 AS DECIMAL(10,2)),
    MB_Si_Deduplicado   = CAST((SELECT SUM(CAST(DATALENGTH(x.IMG_ICONO) AS BIGINT))
                                FROM (SELECT DISTINCT HASHBYTES('SHA2_256', CAST(c2.IMG_ICONO AS VARBINARY(MAX))) AS h,
                                             MIN(DATALENGTH(c2.IMG_ICONO)) AS len_dummy
                                      FROM SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES a2
                                      INNER JOIN SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES_BOTONES b2
                                              ON a2.COD_ROL_USUARIO = b2.COD_ROL_USUARIO
                                             AND a2.COD_APLICACION = b2.COD_APLICACION
                                             AND a2.COD_OPCION_APLICACION = b2.COD_OPCION_APLICACION
                                      INNER JOIN SEGURIDAD.APLICACIONES_OPCIONES_BOTONES c2
                                              ON b2.COD_APLICACION = c2.COD_APLICACION
                                             AND b2.COD_OPCION_APLICACION = c2.COD_OPCION_APLICACION
                                             AND b2.COD_BOTON_OPCION = c2.COD_BOTON_OPCION
                                      WHERE a2.COD_ROL_USUARIO = @COD_ROL_USUARIO
                                        AND c2.IMG_ICONO IS NOT NULL
                                      GROUP BY HASHBYTES('SHA2_256', CAST(c2.IMG_ICONO AS VARBINARY(MAX)))) d
                                CROSS APPLY (SELECT TOP 1 c3.IMG_ICONO
                                             FROM SEGURIDAD.APLICACIONES_OPCIONES_BOTONES c3
                                             WHERE HASHBYTES('SHA2_256', CAST(c3.IMG_ICONO AS VARBINARY(MAX))) = d.h) x
                               ) / 1048576.0 AS DECIMAL(10,2))
FROM SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES a
INNER JOIN SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES_BOTONES b
        ON a.COD_ROL_USUARIO = b.COD_ROL_USUARIO
       AND a.COD_APLICACION = b.COD_APLICACION
       AND a.COD_OPCION_APLICACION = b.COD_OPCION_APLICACION
INNER JOIN SEGURIDAD.APLICACIONES_OPCIONES_BOTONES c
        ON b.COD_APLICACION = c.COD_APLICACION
       AND b.COD_OPCION_APLICACION = c.COD_OPCION_APLICACION
       AND b.COD_BOTON_OPCION = c.COD_BOTON_OPCION
WHERE a.COD_ROL_USUARIO = @COD_ROL_USUARIO;


PRINT '=== 2) OPCIONES ===';

SELECT
    Filas_Enviadas   = COUNT(*),
    Iconos_Distintos = COUNT(DISTINCT HASHBYTES('SHA2_256', CAST(d.IMG_ICONO AS VARBINARY(MAX)))),
    MB_Enviados      = CAST(SUM(CAST(DATALENGTH(d.IMG_ICONO) AS BIGINT)) / 1048576.0 AS DECIMAL(10,2))
FROM SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES a
INNER JOIN SEGURIDAD.APLICACIONES_OPCIONES d
        ON a.COD_APLICACION = d.COD_APLICACION
       AND a.COD_OPCION_APLICACION = d.COD_OPCION_APLICACION
WHERE a.COD_ROL_USUARIO = @COD_ROL_USUARIO;


PRINT '=== 3) APLICACIONES ===';

SELECT
    Filas_Enviadas   = COUNT(*),
    Iconos_Distintos = COUNT(DISTINCT HASHBYTES('SHA2_256', CAST(b.IMG_ICONO AS VARBINARY(MAX)))),
    MB_Enviados      = CAST(SUM(CAST(DATALENGTH(b.IMG_ICONO) AS BIGINT)) / 1048576.0 AS DECIMAL(10,2))
FROM SEGURIDAD.ROLES_USUARIO_APLICACIONES a
INNER JOIN SEGURIDAD.APLICACIONES b
        ON a.COD_APLICACION = b.COD_APLICACION
WHERE a.COD_ROL_USUARIO = @COD_ROL_USUARIO;


PRINT '=== 4) LOS 20 ÍCONOS DE BOTÓN MÁS REPETIDOS ===';
/* Si esta lista muestra pocos íconos con MUCHAS repeticiones, la hipótesis
   del diagnóstico queda confirmada: hay que deduplicar o servirlos como
   recursos HTTP cacheables. */

SELECT TOP 20
    Veces_Repetido = COUNT(*),
    KB_Por_Copia   = CAST(MIN(DATALENGTH(c.IMG_ICONO)) / 1024.0 AS DECIMAL(10,2)),
    KB_Desperdiciados = CAST((COUNT(*) - 1) * MIN(DATALENGTH(c.IMG_ICONO)) / 1024.0 AS DECIMAL(10,2)),
    Ejemplo_Boton  = MIN(c.DES_BOTON_OPCION)
FROM SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES a
INNER JOIN SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES_BOTONES b
        ON a.COD_ROL_USUARIO = b.COD_ROL_USUARIO
       AND a.COD_APLICACION = b.COD_APLICACION
       AND a.COD_OPCION_APLICACION = b.COD_OPCION_APLICACION
INNER JOIN SEGURIDAD.APLICACIONES_OPCIONES_BOTONES c
        ON b.COD_APLICACION = c.COD_APLICACION
       AND b.COD_OPCION_APLICACION = c.COD_OPCION_APLICACION
       AND b.COD_BOTON_OPCION = c.COD_BOTON_OPCION
WHERE a.COD_ROL_USUARIO = @COD_ROL_USUARIO
  AND c.IMG_ICONO IS NOT NULL
GROUP BY HASHBYTES('SHA2_256', CAST(c.IMG_ICONO AS VARBINARY(MAX)))
ORDER BY COUNT(*) DESC;


PRINT '=== 5) TOTAL GENERAL DEL PAYLOAD DE ICONOS (los 3 resultados juntos) ===';
/* Recordá: sobre este total hay que sumar ~33% porque en JSON viaja en Base64. */

SELECT Total_MB_Binario = CAST((
      ISNULL((SELECT SUM(CAST(DATALENGTH(c.IMG_ICONO) AS BIGINT))
              FROM SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES a
              INNER JOIN SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES_BOTONES b
                      ON a.COD_ROL_USUARIO=b.COD_ROL_USUARIO AND a.COD_APLICACION=b.COD_APLICACION AND a.COD_OPCION_APLICACION=b.COD_OPCION_APLICACION
              INNER JOIN SEGURIDAD.APLICACIONES_OPCIONES_BOTONES c
                      ON b.COD_APLICACION=c.COD_APLICACION AND b.COD_OPCION_APLICACION=c.COD_OPCION_APLICACION AND b.COD_BOTON_OPCION=c.COD_BOTON_OPCION
              WHERE a.COD_ROL_USUARIO=@COD_ROL_USUARIO), 0)
    + ISNULL((SELECT SUM(CAST(DATALENGTH(d.IMG_ICONO) AS BIGINT))
              FROM SEGURIDAD.ROLES_USUARIOS_APLICACIONES_OPCIONES a
              INNER JOIN SEGURIDAD.APLICACIONES_OPCIONES d
                      ON a.COD_APLICACION=d.COD_APLICACION AND a.COD_OPCION_APLICACION=d.COD_OPCION_APLICACION
              WHERE a.COD_ROL_USUARIO=@COD_ROL_USUARIO), 0)
    + ISNULL((SELECT SUM(CAST(DATALENGTH(b.IMG_ICONO) AS BIGINT))
              FROM SEGURIDAD.ROLES_USUARIO_APLICACIONES a
              INNER JOIN SEGURIDAD.APLICACIONES b ON a.COD_APLICACION=b.COD_APLICACION
              WHERE a.COD_ROL_USUARIO=@COD_ROL_USUARIO), 0)
    ) / 1048576.0 AS DECIMAL(10,2));
