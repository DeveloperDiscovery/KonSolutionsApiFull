using Microsoft.AspNetCore.Authorization;
using KonSolutionsApi.API.Filters;
using Microsoft.AspNetCore.Mvc;
using KonSolutionsApi.Application.Interfaces;
using KonSolutionsApi.Domain.Models.Networking;

namespace KonSolutionsApi.API.Controllers;

[Authorize]
[Route("api/v1/networking/categorias-comision")]
[ExigePermiso("NETWORKING.CATEGORIAS_COMISION")]
public class CategoriasComisionController : BaseController
{
    private readonly ICategoriasComisionService _service;
    public CategoriasComisionController(ICategoriasComisionService service) => _service = service;

    [HttpGet]
    public async Task<IActionResult> GetAll()
    { var r = await _service.GetAllAsync(); return r.Success ? Ok(r) : BadRequest(r); }

    [HttpGet("{COD_CATEGORIA_COMISION}")]
    public async Task<IActionResult> GetById(string COD_CATEGORIA_COMISION)
    { var r = await _service.GetByIdAsync(COD_CATEGORIA_COMISION); return r.Success ? Ok(r) : NotFound(r); }

    [HttpGet("combobox")]
    public async Task<IActionResult> GetCombobox()
    { var r = await _service.GetComboboxAsync(); return r.Success ? Ok(r) : BadRequest(r); }

    [HttpGet("search")]
    public async Task<IActionResult> Search([FromQuery] CategoriasComisionSearchDto dto)
    { var r = await _service.SearchAsync(dto); return r.Success ? Ok(r) : BadRequest(r); }

    // POST = crear, PUT = modificar. El SP _INSERT ya no hace upsert.
    [HttpPost]
    public async Task<IActionResult> Insert([FromBody] CategoriasComisionInsertDto dto)
    { if (!ModelState.IsValid) return BadRequest(ModelState);
      var r = await _service.InsertAsync(dto, GetCodUsuario(), GetEstacion());
      return r.Success ? StatusCode(201, r) : BadRequest(r); }

    [HttpPut]
    public async Task<IActionResult> Update([FromBody] CategoriasComisionUpdateDto dto)
    { if (!ModelState.IsValid) return BadRequest(ModelState);
      var r = await _service.UpdateAsync(dto, GetCodUsuario(), GetEstacion());
      return r.Success ? Ok(r) : BadRequest(r); }

    [HttpDelete("{COD_CATEGORIA_COMISION}")]
    public async Task<IActionResult> Delete(string COD_CATEGORIA_COMISION)
    { var r = await _service.DeleteAsync(COD_CATEGORIA_COMISION); return r.Success ? Ok(r) : BadRequest(r); }

}